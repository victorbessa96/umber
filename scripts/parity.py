#!/usr/bin/env python3
"""Generate docs/parity.md from docs/specs/requirements.md.

The requirements file is the source of truth. This generator only renders a
reviewable parity view and can verify that the checked-in file is current.
Stdlib-only: no third-party dependencies.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_REQUIREMENTS = ROOT / "docs" / "specs" / "requirements.md"
DEFAULT_OUTPUT = ROOT / "docs" / "parity.md"


def split_markdown_row(raw):
    r"""Split a table row on unescaped pipes and unescape literal `\|`."""
    body = raw.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        backslashes = 0
        index = len(body) - 2
        while index >= 0 and body[index] == "\\":
            backslashes += 1
            index -= 1
        if backslashes % 2 == 0:
            body = body[:-1]

    cells = []
    cell = []
    index = 0
    while index < len(body):
        char = body[index]
        if char == "\\":
            end = index
            while end < len(body) and body[end] == "\\":
                end += 1
            count = end - index
            if end < len(body) and body[end] == "|" and count % 2 == 1:
                cell.extend("\\" * (count - 1))
                cell.append("|")
                index = end + 1
                continue
            cell.extend("\\" * count)
            index = end
            continue
        if char == "|":
            cells.append("".join(cell).strip())
            cell = []
        else:
            cell.append(char)
        index += 1
    cells.append("".join(cell).strip())
    return cells


def parse_requirements(text):
    sections = []
    section = None
    for line_number, raw in enumerate(text.splitlines(), start=1):
        if raw.startswith("## "):
            section = {"title": raw[3:].strip(), "rows": [], "table_kind": None}
            sections.append(section)
            continue
        if section is None or not raw.startswith("|"):
            continue
        cells = split_markdown_row(raw)
        if not cells:
            continue
        first = cells[0].lower()
        if first in {"requirement", "budget"}:
            section["table_kind"] = first
            continue
        if first.startswith("---"):
            continue
        table_kind = section["table_kind"]
        legacy_budget_status = (
            table_kind == "budget"
            and len(cells) >= 3
            and cells[2].startswith(("✓", "◐"))
        )
        if table_kind != "requirement" and not legacy_budget_status:
            continue
        if len(cells) < 3:
            raise ValueError(f"malformed requirement row at line {line_number}: {raw}")
        if len(cells) >= 4:
            wave, status = cells[2], cells[3]
        elif cells[2].startswith(("✓", "◐")):
            # Older budget rows have Requirement, Target, Status and no Wave.
            wave, status = "—", cells[2]
        else:
            # A missing status cell is open, never a dropped row.
            wave, status = cells[2], "OPEN"
        section["rows"].append((cells[0], cells[1], wave, status))
    return sections


def status_kind(status):
    if "◐" in status:
        return "partial"
    if "✓" in status:
        return "built"
    return "open"


def escape_cell(text):
    return text.replace("|", "\\|")


def render(sections):
    rows = [row for section in sections for row in section["rows"]]
    if not rows:
        raise ValueError("no requirement rows found")
    counts = {"built": 0, "partial": 0, "open": 0}
    for _, _, _, status in rows:
        counts[status_kind(status)] += 1
    total = len(rows)
    lines = [
        "# Umber — capability parity",
        "",
        "<!-- Generated by scripts/parity.py; do not edit manually. -->",
        "",
        (
            f"Total requirements: {total} "
            f"({counts['built']} built, {counts['partial']} partial, {counts['open']} open)."
        ),
        "",
        "Source: `docs/specs/requirements.md` (authoritative).",
        "",
    ]
    for section in sections:
        lines.extend(
            [
                f"## {section['title']}",
                "",
                "| Requirement | Priority | Wave | Status |",
                "|---|---|---|---|",
            ]
        )
        for requirement, priority, wave, status in section["rows"]:
            lines.append(
                f"| {escape_cell(requirement)} | {escape_cell(priority)} | "
                f"{escape_cell(wave)} | {escape_cell(status)} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def generate(requirements_path):
    text = requirements_path.read_text(encoding="utf-8")
    return render(parse_requirements(text))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", type=Path, default=DEFAULT_REQUIREMENTS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    try:
        expected = generate(args.requirements).encode("utf-8")
        if args.check:
            if not args.output.is_file():
                print(f"parity: missing output {args.output}", file=sys.stderr)
                return 1
            actual = args.output.read_bytes()
            if actual != expected:
                print(f"parity: STALE output {args.output}", file=sys.stderr)
                return 1
            print("parity: current")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
            print(f"parity: wrote {args.output}")
        return 0
    except (OSError, ValueError) as exc:
        print(f"parity: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
